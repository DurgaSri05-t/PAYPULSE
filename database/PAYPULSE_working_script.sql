SHOW DATABASES;
CREATE DATABASE IF NOT EXISTS PAYPULSE;
USE PAYPULSE;

--  CUSTOMERS TABLE

CREATE TABLE CUSTOMERS (
    CUSTOMER_ID INT PRIMARY KEY AUTO_INCREMENT,
    CUSTOMER_NAME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(100) UNIQUE NOT NULL,
    PHONE VARCHAR(15),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
DESCRIBE CUSTOMERS;

--  MERCHANTS TABLE

CREATE TABLE MERCHANTS (
    MERCHANT_ID INT PRIMARY KEY AUTO_INCREMENT,
    MERCHANT_NAME VARCHAR(100) NOT NULL,
    BUSINESS_TYPE VARCHAR(50) NOT NULL,
    EMAIL VARCHAR(100) UNIQUE,
    PHONE VARCHAR(15),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
DESCRIBE MERCHANTS;

--  PAYMENT GATEWAYS TABLE

CREATE TABLE PAYMENT_GATEWAYS (
    GATEWAY_ID INT PRIMARY KEY AUTO_INCREMENT,
    GATEWAY_NAME VARCHAR(100) NOT NULL,
    GATEWAY_TYPE VARCHAR(50),
    SUPPORT_EMAIL VARCHAR(100),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
DESCRIBE PAYMENT_GATEWAYS;

--  PAYMENT METHODS TABLE

CREATE TABLE PAYMENT_METHODS (
    METHOD_ID INT PRIMARY KEY AUTO_INCREMENT,
    METHOD_NAME VARCHAR(50) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR(200),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
DESCRIBE PAYMENT_METHODS;

--  TRANSACTION STATUSES TABLE

CREATE TABLE TRANSACTION_STATUSES (
    STATUS_ID INT PRIMARY KEY AUTO_INCREMENT,
    STATUS_NAME VARCHAR(30) NOT NULL UNIQUE,
    DESCRIPTION VARCHAR(200)
);
DESCRIBE TRANSACTION_STATUSES;

--  TRANSACTIONS TABLE

CREATE TABLE TRANSACTIONS (
    TRANSACTION_ID INT PRIMARY KEY AUTO_INCREMENT,
    TRANSACTION_REFERENCE VARCHAR(50) UNIQUE NOT NULL,
    CUSTOMER_ID INT NOT NULL,
    MERCHANT_ID INT NOT NULL,
    GATEWAY_ID INT NOT NULL,
    METHOD_ID INT NOT NULL,
    STATUS_ID INT NOT NULL,
    AMOUNT DECIMAL(12,2) NOT NULL,
    TRANSACTION_TIME TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (CUSTOMER_ID)REFERENCES CUSTOMERS(CUSTOMER_ID),
    FOREIGN KEY (MERCHANT_ID)REFERENCES MERCHANTS(MERCHANT_ID),
    FOREIGN KEY (GATEWAY_ID)REFERENCES PAYMENT_GATEWAYS(GATEWAY_ID),
    FOREIGN KEY (METHOD_ID)REFERENCES PAYMENT_METHODS(METHOD_ID),
    FOREIGN KEY (STATUS_ID)REFERENCES TRANSACTION_STATUSES(STATUS_ID),
    CHECK (AMOUNT > 0)
);
DESCRIBE TRANSACTIONS;

--  REFUNDS TABLE

CREATE TABLE REFUNDS (
    REFUND_ID INT PRIMARY KEY AUTO_INCREMENT,
    TRANSACTION_ID INT NOT NULL,
    REFUND_REFERENCE VARCHAR(50) UNIQUE NOT NULL,
    REFUND_AMOUNT DECIMAL(12,2) NOT NULL,
    REFUND_REQUESTED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    REFUND_PROCESSED_AT TIMESTAMP NULL,
    REFUND_STATUS VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    FOREIGN KEY (TRANSACTION_ID)REFERENCES TRANSACTIONS(TRANSACTION_ID),
    CHECK (REFUND_AMOUNT > 0),CHECK (REFUND_STATUS IN('REQUESTED', 'PROCESSING', 'COMPLETED', 'REJECTED'))
);
DESCRIBE REFUNDS;

-- 1.12 TRANSACTION STATUS HISTORY TABLE

CREATE TABLE TRANSACTION_STATUS_HISTORY (
    HISTORY_ID INT PRIMARY KEY AUTO_INCREMENT,
    TRANSACTION_ID INT NOT NULL,
    OLD_STATUS_ID INT,
    NEW_STATUS_ID INT NOT NULL,
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    REMARKS VARCHAR(200),
    FOREIGN KEY (TRANSACTION_ID)REFERENCES TRANSACTIONS(TRANSACTION_ID),
    FOREIGN KEY (OLD_STATUS_ID)REFERENCES TRANSACTION_STATUSES(STATUS_ID),
    FOREIGN KEY (NEW_STATUS_ID)REFERENCES TRANSACTION_STATUSES(STATUS_ID)
);
DESCRIBE TRANSACTION_STATUS_HISTORY;

