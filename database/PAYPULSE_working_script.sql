-- VIEWS

-- VIEW 1: FAILED TRANSACTIONS

CREATE VIEW VW_FAILED_TRANSACTIONS AS
SELECT
    T.TRANSACTION_ID,
    T.TRANSACTION_REFERENCE,
    C.CUSTOMER_NAME,
    M.MERCHANT_NAME,
    G.GATEWAY_NAME,
    PM.METHOD_NAME,
    T.AMOUNT,
    T.TRANSACTION_TIME
FROM TRANSACTIONS T
JOIN CUSTOMERS C ON T.CUSTOMER_ID = C.CUSTOMER_ID
JOIN MERCHANTS M ON T.MERCHANT_ID = M.MERCHANT_ID
JOIN PAYMENT_GATEWAYS G ON T.GATEWAY_ID = G.GATEWAY_ID
JOIN PAYMENT_METHODS PM ON T.METHOD_ID = PM.METHOD_ID
JOIN TRANSACTION_STATUSES S ON T.STATUS_ID = S.STATUS_ID
WHERE S.STATUS_NAME = 'FAILED';
SELECT * FROM VW_FAILED_TRANSACTIONS;

-- VIEW 2: REFUND ANALYTICS

CREATE VIEW VW_REFUND_ANALYTICS AS
SELECT
    R.REFUND_ID,
    R.REFUND_REFERENCE,
    T.TRANSACTION_REFERENCE,
    C.CUSTOMER_NAME,
    M.MERCHANT_NAME,
    T.AMOUNT AS TRANSACTION_AMOUNT,
    R.REFUND_AMOUNT,
    R.REFUND_STATUS,
    R.REFUND_REQUESTED_AT,
    R.REFUND_PROCESSED_AT
FROM REFUNDS R
JOIN TRANSACTIONS T ON R.TRANSACTION_ID = T.TRANSACTION_ID
JOIN CUSTOMERS C ON T.CUSTOMER_ID = C.CUSTOMER_ID
JOIN MERCHANTS M ON T.MERCHANT_ID = M.MERCHANT_ID;
SELECT * FROM VW_REFUND_ANALYTICS;

-- VIEW 3: MERCHANT PAYMENT SUMMARY

CREATE VIEW VW_MERCHANT_PAYMENT_SUMMARY AS
SELECT
    M.MERCHANT_ID,
    M.MERCHANT_NAME,
    COUNT(T.TRANSACTION_ID) AS TOTAL_TRANSACTIONS,
    SUM(CASE WHEN S.STATUS_NAME = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESS_COUNT,
    SUM(CASE WHEN S.STATUS_NAME = 'FAILED' THEN 1 ELSE 0 END) AS FAILED_COUNT,
    SUM(T.AMOUNT) AS TOTAL_TRANSACTION_AMOUNT
FROM MERCHANTS M
LEFT JOIN TRANSACTIONS T ON M.MERCHANT_ID = T.MERCHANT_ID
LEFT JOIN TRANSACTION_STATUSES S ON T.STATUS_ID = S.STATUS_ID
GROUP BY M.MERCHANT_ID, M.MERCHANT_NAME;
SELECT * FROM VW_MERCHANT_PAYMENT_SUMMARY;

-- SECTION 5: STORED PROCEDURES

-- PROCEDURE 1: GET TRANSACTIONS BY STATUS

CREATE PROCEDURE SP_GET_TRANSACTIONS_BY_STATUS(
    IN P_STATUS_NAME VARCHAR(30)
)
SELECT
    T.TRANSACTION_ID,
    T.TRANSACTION_REFERENCE,
    C.CUSTOMER_NAME,
    M.MERCHANT_NAME,
    T.AMOUNT,
    S.STATUS_NAME,
    T.TRANSACTION_TIME
FROM TRANSACTIONS T
JOIN CUSTOMERS C ON T.CUSTOMER_ID = C.CUSTOMER_ID
JOIN MERCHANTS M ON T.MERCHANT_ID = M.MERCHANT_ID
JOIN TRANSACTION_STATUSES S ON T.STATUS_ID = S.STATUS_ID
WHERE S.STATUS_NAME = P_STATUS_NAME;
CALL SP_GET_TRANSACTIONS_BY_STATUS('FAILED');

-- PROCEDURE 2: CUSTOMER TRANSACTION SUMMARY

CREATE PROCEDURE SP_CUSTOMER_TRANSACTION_SUMMARY(
    IN P_CUSTOMER_ID INT
)
SELECT
    C.CUSTOMER_ID,
    C.CUSTOMER_NAME,
    COUNT(T.TRANSACTION_ID) AS TOTAL_TRANSACTIONS,
    COALESCE(SUM(T.AMOUNT), 0) AS TOTAL_AMOUNT,
    SUM(CASE WHEN S.STATUS_NAME = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESS_COUNT,
    SUM(CASE WHEN S.STATUS_NAME = 'FAILED' THEN 1 ELSE 0 END) AS FAILED_COUNT
FROM CUSTOMERS C
LEFT JOIN TRANSACTIONS T ON C.CUSTOMER_ID = T.CUSTOMER_ID
LEFT JOIN TRANSACTION_STATUSES S ON T.STATUS_ID = S.STATUS_ID
WHERE C.CUSTOMER_ID = P_CUSTOMER_ID
GROUP BY C.CUSTOMER_ID, C.CUSTOMER_NAME;

CALL SP_CUSTOMER_TRANSACTION_SUMMARY(1);

-- PROCEDURE 3: MERCHANT TRANSACTION SUMMARY

CREATE PROCEDURE SP_MERCHANT_TRANSACTION_SUMMARY(
    IN P_MERCHANT_ID INT
)
SELECT
    M.MERCHANT_ID,
    M.MERCHANT_NAME,
    COUNT(T.TRANSACTION_ID) AS TOTAL_TRANSACTIONS,
    SUM(CASE WHEN S.STATUS_NAME = 'SUCCESS' THEN 1 ELSE 0 END) AS SUCCESS_COUNT,
    SUM(CASE WHEN S.STATUS_NAME = 'FAILED' THEN 1 ELSE 0 END) AS FAILED_COUNT,
    COALESCE(SUM(T.AMOUNT), 0) AS TOTAL_TRANSACTION_AMOUNT
FROM MERCHANTS M
LEFT JOIN TRANSACTIONS T ON M.MERCHANT_ID = T.MERCHANT_ID
LEFT JOIN TRANSACTION_STATUSES S ON T.STATUS_ID = S.STATUS_ID
WHERE M.MERCHANT_ID = P_MERCHANT_ID
GROUP BY M.MERCHANT_ID, M.MERCHANT_NAME;
CALL SP_MERCHANT_TRANSACTION_SUMMARY(1);
